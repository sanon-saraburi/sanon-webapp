-- เพิ่มคอลัมน์ cert_status ในตาราง leave_requests — สถานะใบรับรองแพทย์ (เฉพาะลาป่วย)
-- แนวทาง C: ไม่เก็บไฟล์จริง เก็บแค่สถานะ พนักงานนำใบจริงมาส่งแยกต่างหากนอกระบบ
-- รันใน Supabase SQL Editor (หลังจาก leave_schema.sql แล้ว)
-- วันที่: 2026-10-01

ALTER TABLE leave_requests ADD COLUMN IF NOT EXISTS cert_status TEXT DEFAULT NULL;

COMMENT ON COLUMN leave_requests.cert_status IS
  'สถานะใบรับรองแพทย์ (เฉพาะลาป่วย type_code=sick) — ค่าที่ใช้: "มีใบ" | "ไม่มี" | "จะนำมาส่งภายหลัง" | NULL (การลาประเภทอื่น)';

-- หมายเหตุ:
-- * ฟิลด์นี้เป็น TEXT ธรรมดา ไม่ได้บังคับด้วย CHECK constraint (สอดคล้องกับ style ฟิลด์สถานะอื่นในตาราง เช่น status, half_day)
-- * ไม่มีการเปลี่ยนแปลง RLS — policy anon_all เดิมครอบคลุมคอลัมน์ใหม่นี้อยู่แล้ว ไม่ต้องรันเพิ่ม
-- * โค้ดฝั่ง leave.html: ฟอร์ม "ยื่นคำขอลา" บังคับเลือกสถานะนี้เมื่อประเภทลา = ลาป่วย,
--   Admin แก้ไขสถานะภายหลังได้ที่ปุ่ม "แก้ไข" ในหน้า "อนุมัติคำขอลา" (เช่น เปลี่ยนจาก "จะนำมาส่งภายหลัง" เป็น "มีใบ" เมื่อพนักงานนำใบจริงมาส่ง)
-- * หน้า "อนุมัติคำขอลา" จะแสดง badge "⏳ รอใบรับรองแพทย์" ให้อัตโนมัติ สำหรับคำขอลาป่วยที่สถานะเป็น "จะนำมาส่งภายหลัง"
